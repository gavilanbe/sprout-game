/* tildes y diéresis: se componen sobre el glifo base */
const ACCENTS={'Á':['A','´'],'É':['E','´'],'Í':['I','´'],'Ó':['O','´'],'Ú':['U','´'],'Ü':['U','¨'],'Ñ':['N','~'],
  'á':['a','´'],'é':['e','´'],'í':['ı','´'],'ó':['o','´'],'ú':['u','´'],'ü':['u','¨'],'ö':['o','¨'],'ñ':['n','~']};
GLYPHS_M['ı']=["..","..","#.","#.","#.","#.","#."]; // i sin punto (para la í)
const FONT_M={glyphs:GLYPHS_M, asc:3, h:9, space:3, cache:new Map(), atlas:null, map:{}};
const FONT_S={glyphs:GLYPHS_S, asc:0, h:5, space:2, cache:new Map(), atlas:null, map:{}, caps:true};
function buildFont(F){
  const chars=Object.keys(F.glyphs).concat(Object.keys(ACCENTS));
  let x=0; const cellH=F.h+F.asc+1;
  const list=chars.map(ch=>{ let base=ch, acc=null;
    if(ACCENTS[ch]){ [base,acc]=ACCENTS[ch]; if(F.caps) base=base.toUpperCase().replace('ı','I'); }
    const rows=F.glyphs[base]; if(!rows) return null;
    const w=rows[0].length, o={ch,x,w,rows,acc}; x+=w+1; return o; }).filter(Boolean);
  const cv=mkCanvas(x+1,cellH), g=cv.getContext('2d'); g.fillStyle='#ffffff';
  for(const o of list){
    o.rows.forEach((r,y)=>{ for(let i=0;i<r.length;i++) if(r[i]==='#') g.fillRect(o.x+i,y+F.asc,1,1); });
    if(o.acc&&!F.caps){ // mayúsculas: tilde en las 2 filas sobre la caja (con 1 de aire); minúsculas: sobre la x
      const lower=o.ch===o.ch.toLowerCase(), top=lower?F.asc-1:0, mid=o.ch==='í'?o.x:o.x+(o.w>>1);
      if(o.acc==='´'){ g.fillRect(mid,top+1,1,1); g.fillRect(mid+1,top,1,1); }
      else if(o.acc==='¨'){ g.fillRect(o.x,top+1,1,1); g.fillRect(o.x+o.w-1,top+1,1,1); }
      else if(o.acc==='~'){ for(let i=0;i<o.w;i++) g.fillRect(o.x+i,top+((i&1)?0:1),1,1); } }
    F.map[o.ch]=o; }
  F.atlas=cv;
}
buildFont(FONT_M); buildFont(FONT_S);
function fontAtlas(F,col){ let c=F.cache.get(col); if(!c){ c=tintTo(F.atlas,col); F.cache.set(col,c); } return c; }
function glyphOf(F,ch){ if(F.caps) ch=ch.toUpperCase(); return F.map[ch]||(F.caps?F.map[ch.normalize('NFD')[0]]:null); }
function textW(s,F){ F=F||FONT_M; let w=0; for(const ch of String(s)){ if(ch===' '){ w+=F.space+1; continue; } const o=glyphOf(F,ch); w+=o?o.w+1:F.space+1; } return Math.max(0,w-1); }
/* pinta s con la parte alta de la mayúscula en y; align: left|center|right */
function drawText(g,s,x,y,col,align,F){
  F=F||FONT_M; s=String(s); if(align==='center') x-=textW(s,F)>>1; else if(align==='right') x-=textW(s,F);
  x=Math.round(x); y=Math.round(y)-F.asc; const A=fontAtlas(F,col||'#fffbe8'), H=F.h+F.asc+1;
  for(const ch of s){ if(ch===' '){ x+=F.space+1; continue; } const o=glyphOf(F,ch); if(!o){ x+=F.space+1; continue; }
    g.drawImage(A,o.x,0,o.w,H,x,y,o.w,H); x+=o.w+1; }
  return x;
}
/* ajuste de líneas por ancho real en píxeles */
function wrapPx(s,maxW,F){
  const out=[]; F=F||FONT_M;
  for(const raw of String(s).split('\n')){ const words=raw.split(' '); let ln='';
    for(const w of words){ const t=ln?ln+' '+w:w; if(textW(t,F)<=maxW||!ln) ln=t; else { out.push(ln); ln=w; } }
    out.push(ln); }
  return out;
}
